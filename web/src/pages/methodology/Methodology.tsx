export function Methodology() {
  useTitle("Methodology");
  const { experiments } = useResearch();
  const resolved = stages.map((stage) => ({ ...stage, shown: stageStatus(stage, experiments) }));
  const counts = resolved.reduce<Record<StageStatus, number>>(
    (acc, st) => ({ ...acc, [st.shown]: acc[st.shown] + 1 }),
    { implemented: 0, proposed: 0, investigating: 0, verified: 0 },
  );

  return (
    <div className={s.page}>
      <header className={`${s.hero} grain`}>
        <div className={s.wrap}>
          <SectionLabel rule>Methodology</SectionLabel>
          <h1 className={`display ${s.heroTitle}`}>
            From twenty-two dots
            <br />
            to <em>who has the ball.</em>
          </h1>
          <p className={s.heroLede}>
            How the system turns automatic tracking into a possession label for every frame. Each stage is marked with its real status in the
            repository, and each claim says whether it is a published finding or our own hypothesis.
          </p>
          <ul className={s.statusLegend} aria-label="Stage status summary">
            {(Object.keys(STAGE_STATUS_TEXT) as StageStatus[]).map((st) => (
              <li key={st} data-status={st}>
                <span className={s.statusDot} aria-hidden="true" />
                <strong>{STAGE_STATUS_TEXT[st].label}</strong>
                <span className="mono">{counts[st]}</span>
                <span className={s.legendDesc}>{STAGE_STATUS_TEXT[st].description}</span>
              </li>
            ))}
          </ul>
        </div>
      </header>

      <section className={s.pipeline} aria-labelledby="pipeline-title">
        <div className={s.wrap}>
          <div className={s.sectionHead}>
            <SectionLabel>The pipeline</SectionLabel>
            <h2 id="pipeline-title" className={`display ${s.h2}`}>
              Eight stages
            </h2>
            <p>
              None is verified yet, because no full-match run of the official scorer has been recorded. A stage moves to verified automatically
              when one of its linked experiments holds a verified full-match metric.
            </p>
          </div>
          <ol className={s.stages}>
            {resolved.map((stage) => (
              <li key={stage.id} className={s.stage} data-status={stage.shown}>
                <span className={`mono ${s.stageNo}`}>{String(stage.number).padStart(2, "0")}</span>
                <div className={s.stageMain}>
                  <div className={s.stageHead}>
                    <h3>{stage.title}</h3>
                    <span className={s.stageStatus} data-status={stage.shown}>
                      <span className={s.statusDot} aria-hidden="true" />
                      {STAGE_STATUS_TEXT[stage.shown].label}
                    </span>
                  </div>
                  <p className={s.stageSummary}>{stage.summary}</p>
                  <p className={s.stageDetail}>{stage.detail}</p>
                  {stage.evidence.length > 0 && (
                    <ul className={s.evidence} aria-label="Evidence">
                      {stage.evidence.map((ev) => (
                        <li key={ev.ref + ev.label}>
                          <span>{ev.label}</span>
                          <code>{ev.ref}</code>
                        </li>
                      ))}
                    </ul>
                  )}
                  {stage.caveat && <p className={s.caveat}>{stage.caveat}</p>}
                </div>
              </li>
            ))}
          </ol>
        </div>
      </section>

      <section className={s.principles} aria-labelledby="principles-title">
        <div className={s.wrap}>
          <div className={s.sectionHead}>
            <SectionLabel>Why it's hard</SectionLabel>
            <h2 id="principles-title" className={`display ${s.h2Cream}`}>
              Seven things the <em>problem</em> teaches you
            </h2>
          </div>
          <div className={s.principleGrid}>
            {PRINCIPLES.map((p) => (
              <article key={p.title} className={s.principle} data-claim={p.claim}>
                <span className={s.claim}>{CLAIM_TEXT[p.claim]}</span>
                <h3>{p.title}</h3>
                <p>{p.body}</p>
                <span className={s.source}>{p.source}</span>
              </article>
            ))}
          </div>
        </div>
      </section>

      <section className={s.demoSection}>
        <div className={s.wrap}>
          <SmoothingDemo />
        </div>
      </section>

      <section className={s.next}>
        <div className={`${s.wrap} ${s.nextInner}`}>
          <div>
            <SectionLabel>See it applied</SectionLabel>
            <h2 className={`display ${s.h2}`}>A demo match, read as possessions</h2>
            <p>
              The Match Centre shows the four labels on a synthetic fixture: home, away, dead ball and abstain. It also shows the statistics that come
              from them.
            </p>
          </div>
          <ButtonLink to="/match" tone="primary">
            Open the Match Centre <ArrowRight size={16} aria-hidden="true" />
          </ButtonLink>
        </div>
        <p className={`${s.wrap} ${s.fine}`}>
          Sources are files in the public competition repository. Read <Link to="/">the landing page</Link> for how demo data differs from
          measured results.
        </p>
      </section>
    </div>
  );
}
