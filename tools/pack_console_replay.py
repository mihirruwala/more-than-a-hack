"""Pack the bundled synthetic replay into a compact module for the Match console.

The project site (Figma Make) has no JSON import pipeline and a size budget, so the console there
reads a packed copy of web/src/data/fixtures/liveReplay.json: every 2nd frame (12.5 fps), positions
in decimetres as little-endian int16, base64. The console interpolates between frames when playing.

    python3 tools/pack_console_replay.py

Synthetic data only: the input must be a replay with provenance "synthetic".
"""

import base64
import json
import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "web", "src", "data", "fixtures", "liveReplay.json")
OUT = os.path.join(ROOT, "web", "src", "site", "consoleReplay.ts")
STEP = 2
NA = -32768


def dm(v):
    return NA if v is None else max(-32000, min(32000, round(v * 10)))


def main():
    d = json.load(open(SRC))
    if d.get("provenance") != "synthetic":
        raise SystemExit("refusing to pack a replay that is not synthetic")
    f = d["frames"]
    idx = list(range(0, len(f["label"]), STEP))
    vals = []
    for i in idx:
        vals += [dm(v) for v in f["players"][i]]
        b = f["ball"][i]
        vals += [NA, NA] if b is None else [dm(b[0]), dm(b[1])]
        e = f["est"][i]
        vals += [NA, NA, NA] if e is None else [dm(e[0]), dm(e[1]), NA if e[2] is None else dm(min(e[2], 3000))]
        vals += [round(f["pHome"][i]), round(f["pAway"][i])]
    raw = base64.b64encode(struct.pack("<%dh" % len(vals), *vals)).decode()
    label = "".join(f["label"][i] for i in idx)
    truth = "".join(f["truth"][i] for i in idx)
    with open(OUT, "w") as o:
        o.write("// Generated by tools/pack_console_replay.py from web/src/data/fixtures/liveReplay.json. Do not edit.\n")
        o.write("// A simulated match (not real data), every 2nd frame (12.5 fps). Packed as little-endian int16 per frame:\n")
        o.write("// 22 players x/y, ball x/y, estimate x/y/sigma (decimetres; -32768 = none), p(home), p(away) in %.\n")
        o.write("export const CONSOLE_REPLAY = {\n")
        o.write("  source: {},\n".format(json.dumps(d["source"] + ", every 2nd frame")))
        o.write("  fps: {},\n  pitch: {} as [number, number],\n".format(d["fps"] / STEP, json.dumps(d["pitch"])))
        o.write("  lag: {},\n  teams: {} as (0 | 1)[],\n".format(d["lag"] / STEP, json.dumps(d["teams"])))
        o.write("  firstFrame: {},\n  length: {},\n".format(d["firstFrame"] // STEP, len(idx)))
        o.write('  label: "{}",\n  truth: "{}",\n  packed: [\n'.format(label, truth))
        for k in range(0, len(raw), 120):
            o.write('    "{}",\n'.format(raw[k:k + 120]))
        o.write('  ].join(""),\n};\n')
    print("wrote {} ({} frames, {} KB)".format(os.path.relpath(OUT, ROOT), len(idx), os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    main()
